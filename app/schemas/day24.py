# API requests / status
# ----------------------------------------------------------------------
def _strip_question(value: str) -> str:
    value = (value or "").strip()
    if not value:
        raise ValueError("question must not be blank")
    return value


class Day24AskRequest(Day23Settings):
    """Grounded ask request reuses the Day 23 retrieval knobs.

    ``similarity_threshold`` doubles as the answer gate (Option A, see
    docs/week5/day24.md): a chunk that is not relevant enough for retrieval
    must not be relevant enough to justify an answer.
    """

    question: str = Field(min_length=1, max_length=MAX_QUESTION_LENGTH)

    @field_validator("question")
    @classmethod
    def _strip(cls, value: str) -> str:
        return _strip_question(value)


