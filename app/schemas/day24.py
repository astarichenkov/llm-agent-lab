class Day24EvaluationGradeRecord(BaseModel):
    """One persisted evaluation row.

    ``answer_supported_by_evidence`` is the ONLY human field
    (PASS/PARTIAL/FAIL assigned by the user). The remaining fields are
    written automatically by the evaluation service after each grounded run
    so the summary can be recomputed without re-running the LLM.
    """

    answer_supported_by_evidence: Literal["pass", "partial", "fail"] | None = None

    # Automatic (backend-owned) fields, overwritten on every run.
    status: str | None = None
    has_sources: bool | None = None
    has_quotes: bool | None = None
    all_quotes_valid: bool | None = None
    grounding_valid: bool | None = None


class Day24EvaluationResultsResponse(BaseModel):
    results: dict[str, Day24EvaluationGradeRecord] = Field(default_factory=dict)
    summary: Day24EvaluationSummary


