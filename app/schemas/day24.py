# ----------------------------------------------------------------------
# Source / citation models
# ----------------------------------------------------------------------
class GroundedMessageLink(BaseModel):
    """One message of a Telegram conversation chunk and its permalink.

    ``is_cited`` marks the message the validated quote was actually taken
    from (the main link). Other entries are context links.
    """

    message_id: int
    url: str | None = None
    is_cited: bool = False


class GroundedSource(BaseModel):
    """A real source, reconstructed from retrieved chunk metadata.

    Only fields that actually exist on the chunk are populated; the LLM can
    never add a field here.

    Day 24 addition: ``url`` is resolved by the backend *after* citation
    validation (never generated by the LLM). When no reliable permalink can
    be built it stays ``None`` and the UI shows a non-clickable source.
    """

    source_type: str
    source: str = ""
    chunk_id: str
    title: str = ""
    section: str = ""
    page: int | None = None
    page_from: int | None = None
    page_to: int | None = None
    message_ids: list[int] = Field(default_factory=list)
    date_from: str = ""
    date_to: str = ""
    chat_name: str = ""

    # Backend-resolved source link (optional; None when unavailable).
    url: str | None = None
    cited_message_id: int | None = None
    topic_id: int | None = None
    link_kind: str = ""
    link_note: str = ""
    context_links: list[GroundedMessageLink] = Field(default_factory=list)


class GroundedCitation(BaseModel):
    """One piece of evidence: a chunk_id + a quote + its validation result.

    ``quote_valid`` and ``validation_errors`` are produced by the backend
    CitationValidator, never by the LLM.
    """

    chunk_id: str
    quote: str
    quote_valid: bool
    validation_errors: list[str] = Field(default_factory=list)

    # Real metadata copied from the retrieved chunk (backend-owned).
    source_type: str = ""
    source: str = ""
    title: str = ""
    section: str = ""
    page: int | None = None
    page_from: int | None = None
    page_to: int | None = None
    message_ids: list[int] = Field(default_factory=list)
    date_from: str = ""
    date_to: str = ""
    chat_name: str = ""

    # The full retrieved chunk text ("Show full chunk" in the UI).
    chunk_text: str = ""

    # Backend-resolved source link (optional; None when unavailable).
    url: str | None = None
    cited_message_id: int | None = None
    topic_id: int | None = None
    link_kind: str = ""
    link_note: str = ""
    context_links: list[GroundedMessageLink] = Field(default_factory=list)

    def as_source(self) -> GroundedSource:
        return GroundedSource(
            source_type=self.source_type,
            source=self.source,
            chunk_id=self.chunk_id,
            title=self.title,
            section=self.section,
            page=self.page,
            page_from=self.page_from,
            page_to=self.page_to,
            message_ids=list(self.message_ids),
            date_from=self.date_from,
            date_to=self.date_to,
            chat_name=self.chat_name,
            url=self.url,
            cited_message_id=self.cited_message_id,
            topic_id=self.topic_id,
            link_kind=self.link_kind,
            link_note=self.link_note,
            context_links=list(self.context_links),
        )


