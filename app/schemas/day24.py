"""Pydantic schemas for Week 5 / Day 24 — Grounded RAG and anti-hallucination.

Day 24 keeps the Day 22 baseline and the Day 23 improved pipeline untouched
and adds a *grounded* mode that can prove its answer with retrieved chunks:

    question -> Day 23 improved retrieval -> grounding gate
             -> (refuse) OR (grounded LLM -> structured evidence)
             -> citation validator -> answer + sources + verifiable quotes

The models here are the contract shared by the grounding service, the HTTP
endpoints, the evaluation services and the UI.

A key invariant of the whole module: source metadata (file name, page,
section, message ids) is NEVER taken from the LLM. The LLM may only reference
a ``chunk_id`` that was present in the context; the backend attaches the real
metadata from the retrieved chunk.
"""
from __future__ import annotations

from typing import Literal

from pydantic import BaseModel, Field, field_validator

from app.schemas.day22 import EvaluationQuestion
from app.schemas.day23 import Day23Settings, ImprovedCandidate, RewriteInfo

